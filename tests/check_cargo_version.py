import os
import unittest
from unittest.mock import patch

from hooks.check_cargo_version import (
    CargoIndex,
    main,
    parse_args,
)

from tests._git_fixture import GitRepoFixture

PACKAGE_TEMPLATE = """\
[package]
name = "{name}"
version = "{version}"  # keep this comment
edition = "2021"
"""

INHERITED_TEMPLATE = """\
[package]
name = "{name}"
version.workspace = true
edition = "2021"
"""

NO_VERSION_TEMPLATE = """\
[package]
name = "{name}"
edition = "2021"
"""

WORKSPACE_TEMPLATE = """\
[workspace]
members = ["crates/*"]
resolver = "2"

[workspace.package]
version = "{version}"
"""

LOCK_HEADER = """\
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4
"""

LOCK_ENTRY = """
[[package]]
name = "{name}"
version = "{version}"
"""

LOCK_REGISTRY_ENTRY = """
[[package]]
name = "serde"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"
"""


def _lock(*entries):
    content = LOCK_HEADER

    for name, version in entries:
        content += LOCK_ENTRY.format(name=name, version=version)

    return content + LOCK_REGISTRY_ENTRY


def _run_main(argv):
    with patch("sys.argv", argv):
        try:
            main()
        except SystemExit as e:
            return e.code if e.code is not None else 0

    return 0


class CargoTestCase(unittest.TestCase):
    def setUp(self):
        self.fixture = GitRepoFixture()
        self.cwd = os.getcwd()
        os.chdir(self.fixture.dir)

    def tearDown(self):
        os.chdir(self.cwd)
        self.fixture.cleanup()

    def seed(self, files):
        """Commit files on main and switch to a feature branch."""
        for path, content in files.items():
            self.fixture.write(path, content)

        self.fixture.add(*files.keys())
        self.fixture.commit("seed")
        self.fixture.create_branch("feature")

    def change(self, path, content="// changed\n"):
        self.fixture.write(path, content)
        self.fixture.add(path)

        return path

    def read(self, path):
        with open(os.path.join(self.fixture.dir, path)) as f:
            return f.read()

    def msg_path(self, message):
        path = os.path.join(self.fixture.dir, ".git", "COMMIT_EDITMSG")

        with open(path, "w") as f:
            f.write(message)

        return path


class TestParseArgs(unittest.TestCase):
    def test_defaults(self):
        with patch("sys.argv", ["check_cargo_version.py", "some/path"]):
            args = parse_args()
            self.assertEqual(args.branch, "main")
            self.assertFalse(args.autofix)
            self.assertEqual(args.autofix_strategy, "fixed")
            self.assertEqual(args.autofix_portion, "patch")
            self.assertIn("Cargo", args.include)
            self.assertIsNone(args.exclude)
            self.assertEqual(args.PATH, ["some/path"])


class TestCargoIndex(CargoTestCase):
    def test_owner_and_workspace(self):
        self.seed(
            {
                "Cargo.toml": WORKSPACE_TEMPLATE.format(version="1.0.0"),
                "crates/a/Cargo.toml": INHERITED_TEMPLATE.format(name="a"),
                "crates/a/src/lib.rs": "",
                "crates/b/Cargo.toml": PACKAGE_TEMPLATE.format(
                    name="b", version="2.0.0"
                ),
                "crates/b/Cargo.lock": "",
            }
        )
        index = CargoIndex(self.fixture.repo, None)

        self.assertEqual(index.owner("crates/a/src/lib.rs"), "crates/a")
        self.assertEqual(index.owner("crates/a/Cargo.toml"), "crates/a")
        self.assertIsNone(index.owner("README.md"))
        self.assertEqual(index.workspace_dir("crates/a"), "")
        self.assertEqual(index.inheriting_crates(""), ["crates/a"])


class TestSingleCrate(CargoTestCase):
    def setUp(self):
        super().setUp()
        self.seed(
            {
                "Cargo.toml": PACKAGE_TEMPLATE.format(name="app", version="1.0.0"),
                "Cargo.lock": _lock(("app", "1.0.0")),
                "src/main.rs": "fn main() {}\n",
            }
        )

    def test_fails_when_version_is_not_bumped(self):
        path = self.change("src/main.rs")
        self.assertEqual(_run_main(["x", path]), 127)

    def test_passes_when_version_and_lock_are_bumped(self):
        self.change("Cargo.toml", PACKAGE_TEMPLATE.format(name="app", version="1.0.1"))
        self.change("Cargo.lock", _lock(("app", "1.0.1")))
        path = self.change("src/main.rs")
        self.assertEqual(_run_main(["x", path, "Cargo.toml"]), 0)

    def test_fails_when_lock_is_stale(self):
        self.change("Cargo.toml", PACKAGE_TEMPLATE.format(name="app", version="1.0.1"))
        path = self.change("src/main.rs")
        self.assertEqual(_run_main(["x", path, "Cargo.toml"]), 1)

    def test_autofix_fixes_stale_lock(self):
        self.change("Cargo.toml", PACKAGE_TEMPLATE.format(name="app", version="1.0.1"))
        path = self.change("src/main.rs")
        self.assertEqual(_run_main(["x", "--autofix", path, "Cargo.toml"]), 127)
        self.assertEqual(self.read("Cargo.lock"), _lock(("app", "1.0.1")))

    def test_autofix_bumps_manifest_and_lock(self):
        path = self.change("src/main.rs")
        self.assertEqual(_run_main(["x", "--autofix", path]), 127)
        self.assertEqual(
            self.read("Cargo.toml"),
            PACKAGE_TEMPLATE.format(name="app", version="1.0.1"),
        )
        self.assertEqual(self.read("Cargo.lock"), _lock(("app", "1.0.1")))

    def test_autofix_minor_portion(self):
        path = self.change("src/main.rs")
        argv = ["x", "--autofix", "--autofix-portion=minor", path]
        self.assertEqual(_run_main(argv), 127)
        self.assertIn('version = "1.1.0"', self.read("Cargo.toml"))

    def test_autofix_preserves_literal_string(self):
        self.fixture.write("Cargo.toml", self.read("Cargo.toml").replace('"', "'"))
        path = self.change("src/main.rs")
        self.assertEqual(_run_main(["x", "--autofix", path]), 127)
        self.assertIn("version = '1.0.1'", self.read("Cargo.toml"))

    def test_non_rust_file_is_ignored(self):
        path = self.change("README.md", "changed\n")
        self.assertEqual(_run_main(["x", path]), 0)

    def test_lock_change_is_ignored(self):
        path = self.change("Cargo.lock", _lock(("app", "1.0.0")) + "\n")
        self.assertEqual(_run_main(["x", path]), 0)

    def test_exclude(self):
        path = self.change("tests/it.rs")
        self.assertEqual(_run_main(["x", "--exclude=^tests/", path]), 0)

    def test_deletion_without_bump_fails(self):
        os.remove(os.path.join(self.fixture.dir, "src/main.rs"))
        self.fixture.repo.index.remove(["src/main.rs"])
        self.assertEqual(_run_main(["x"]), 127)

    def test_no_op_at_commit_msg_stage(self):
        self.change("src/main.rs")
        path = self.msg_path("anything\n")
        self.assertEqual(_run_main(["x", path]), 0)


