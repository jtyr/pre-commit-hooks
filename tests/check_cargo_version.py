class TestWorkspace(CargoTestCase):
    def setUp(self):
        super().setUp()
        self.seed(
            {
                "Cargo.toml": WORKSPACE_TEMPLATE.format(version="1.0.0"),
                "Cargo.lock": _lock(("a", "1.0.0"), ("b", "1.0.0"), ("c", "3.0.0")),
                "crates/a/Cargo.toml": INHERITED_TEMPLATE.format(name="a"),
                "crates/a/src/lib.rs": "",
                "crates/b/Cargo.toml": INHERITED_TEMPLATE.format(name="b"),
                "crates/b/src/lib.rs": "",
                "crates/c/Cargo.toml": PACKAGE_TEMPLATE.format(
                    name="c", version="3.0.0"
                ),
                "crates/c/src/lib.rs": "",
            }
        )

    def test_inherited_version_bumps_workspace(self):
        path = self.change("crates/a/src/lib.rs")
        self.assertEqual(_run_main(["x", "--autofix", path]), 127)
        self.assertIn('version = "1.0.1"', self.read("Cargo.toml"))
        self.assertEqual(
            self.read("Cargo.lock"),
            _lock(("a", "1.0.1"), ("b", "1.0.1"), ("c", "3.0.0")),
        )
        self.assertNotIn("version = ", self.read("crates/a/Cargo.toml"))

    def test_own_version_bumps_only_the_crate(self):
        path = self.change("crates/c/src/lib.rs")
        self.assertEqual(_run_main(["x", "--autofix", path]), 127)
        self.assertIn('version = "1.0.0"', self.read("Cargo.toml"))
        self.assertIn('version = "3.0.1"', self.read("crates/c/Cargo.toml"))
        self.assertEqual(
            self.read("Cargo.lock"),
            _lock(("a", "1.0.0"), ("b", "1.0.0"), ("c", "3.0.1")),
        )


class TestConventional(CargoTestCase):
    def setUp(self):
        super().setUp()
        self.seed(
            {
                "Cargo.toml": PACKAGE_TEMPLATE.format(name="app", version="1.0.0")
                + '\n[workspace]\nmembers = ["crates/*"]\n',
                "Cargo.lock": _lock(("app", "1.0.0"), ("foo", "2.0.0")),
                "src/main.rs": "fn main() {}\n",
                "crates/foo/Cargo.toml": PACKAGE_TEMPLATE.format(
                    name="foo", version="2.0.0"
                ),
                "crates/foo/src/lib.rs": "",
            }
        )

    def test_feat_writes_minor_bump(self):
        self.change("crates/foo/src/lib.rs")
        path = self.msg_path("feat: add foo\n")
        argv = ["x", "--autofix", "--autofix-strategy=conventional", path]
        self.assertEqual(_run_main(argv), 127)
        self.assertIn('version = "2.1.0"', self.read("crates/foo/Cargo.toml"))
        self.assertIn('version = "1.0.0"', self.read("Cargo.toml"))
        self.assertEqual(
            self.read("Cargo.lock"), _lock(("app", "1.0.0"), ("foo", "2.1.0"))
        )

    def test_nested_crate_commits_do_not_leak_to_parent(self):
        """A feat: commit on the nested crate must not bump the root crate."""
        self.change("crates/foo/src/lib.rs")
        self.change(
            "crates/foo/Cargo.toml",
            PACKAGE_TEMPLATE.format(name="foo", version="2.1.0"),
        )
        self.change("Cargo.lock", _lock(("app", "1.0.0"), ("foo", "2.1.0")))
        self.fixture.commit("feat: add foo")

        self.change("src/main.rs")
        path = self.msg_path("fix: root\n")
        argv = ["x", "--autofix", "--autofix-strategy=conventional", path]
        self.assertEqual(_run_main(argv), 127)
        self.assertIn('version = "1.0.1"', self.read("Cargo.toml"))
        self.assertIn('version = "2.1.0"', self.read("crates/foo/Cargo.toml"))

    def test_deleted_nested_crate_does_not_affect_parent(self):
        files = ["crates/foo/Cargo.toml", "crates/foo/src/lib.rs"]

        for f in files:
            os.remove(os.path.join(self.fixture.dir, f))

        self.fixture.repo.index.remove(files)
        self.assertEqual(_run_main(["x"]), 0)

    def test_non_cc_message_fails(self):
        self.change("src/main.rs")
        path = self.msg_path("just some text\n")
        argv = ["x", "--autofix-strategy=conventional", path]
        self.assertEqual(_run_main(argv), 1)


if __name__ == "__main__":
    unittest.main()
